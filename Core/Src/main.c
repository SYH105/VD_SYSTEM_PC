void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if(huart->Instance == USART1)
    {
        // =========================
        // 종료 문자 '#' 수신 시
        // =========================
        if(rx_byte == '#')
        {
            cmd_buf[rx_index] = '\0';   // 문자열 종료
            cmd_ready = 1;              // 명령 준비 완료
            rx_index = 0;               // 다음 명령 준비
        }
        else
        {
            // =========================
            // 일반 문자 저장
            // =========================
            if(rx_index < 49)   // 버퍼 오버플로 방지
            {
                cmd_buf[rx_index++] = rx_byte;
            }
        }

        // =========================
        // 다음 바이트 수신 재시작
        // =========================
        HAL_UART_Receive_IT(&huart1, &rx_byte, 1);
    }
}
